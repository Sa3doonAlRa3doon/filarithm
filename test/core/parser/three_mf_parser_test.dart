import 'dart:typed_data';

import 'package:archive/archive.dart';
import 'package:filarithm/core/domain/print_project.dart';
import 'package:filarithm/core/parser/three_mf_parser.dart';
import 'package:flutter_test/flutter_test.dart';

Uint8List archiveWith(Map<String, String> files) {
  final archive = Archive();
  for (final entry in files.entries) {
    archive.add(ArchiveFile.string(entry.key, entry.value));
  }
  return Uint8List.fromList(ZipEncoder().encode(archive));
}

void main() {
  const parser = ThreeMfParser();

  test('parses every embedded plate without extracting arbitrary entries', () {
    final bytes = archiveWith({
      'Metadata/plate_1.gcode': '''
; generated by Bambu Studio 2.0
; filament used [g] = 12.5
; total estimated time = 1h 2m 3s
''',
      'Metadata/plate_2.gcode': '''
; generated by Bambu Studio 2.0
; filament used [g] = 8.25, 4.5
; total estimated time = 42m
''',
      '../not-allowed.txt': 'ignored',
    });

    final result = parser.parseBytes(bytes, sourceName: 'job.3mf');
    expect(result.slicer, SlicerKind.bambuStudio);
    expect(result.plates, hasLength(2));
    expect(result.plates.first.durationSeconds, 3723);
    expect(result.plates.last.durationSeconds, 2520);
    expect(result.plates.last.materials, hasLength(2));
  });

  test('flags an unsliced 3MF instead of inventing statistics', () {
    final bytes = archiveWith({
      '3D/3dmodel.model': '<model><resources /></model>',
    });
    final result = parser.parseBytes(bytes, sourceName: 'model.3mf');

    expect(result.hasUsableStatistics, isFalse);
    expect(
      result.warnings.any(
        (warning) =>
            warning.code == 'unsliced_3mf' &&
            warning.severity == ParseSeverity.error,
      ),
      isTrue,
    );
  });

  test('enforces archive input limit', () {
    const tiny = ThreeMfParser(maxArchiveBytes: 3);
    expect(
      () => tiny.parseBytes(Uint8List(4), sourceName: 'oversize.3mf'),
      throwsFormatException,
    );
  });

  test('rejects excessive expansion ratios before reading metadata', () {
    const strict = ThreeMfParser(maxExpansionRatio: 1);
    final bytes = archiveWith({
      'Metadata/slice_info.config': List.filled(4096, 'A').join(),
    });
    expect(
      () => strict.parseBytes(bytes, sourceName: 'ratio-bomb.3mf'),
      throwsFormatException,
    );
  });

  test('rejects nested archives even when they are not allowlisted', () {
    final bytes = archiveWith({
      'Metadata/nested.zip': 'not-a-real-zip',
      '3D/3dmodel.model': '<model />',
    });
    expect(
      () => parser.parseBytes(bytes, sourceName: 'nested.3mf'),
      throwsFormatException,
    );
  });
}
